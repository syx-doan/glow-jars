const catalogs: Record<Locale, Dict> = { en, vi };

let locale: Locale = "en";

export function getLocale(): Locale {
  return locale;
}

export function setLocale(next: Locale): void {
  locale = next === "vi" ? "vi" : "en";
  document.documentElement.lang = locale;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const table = catalogs[locale] ?? en;
  let text = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function applyStaticI18n(): void {
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (!key) return;
    el.textContent = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    const key = el.dataset.i18nHtml;
    if (!key) return;
    const label = t(key);
    const keep = Array.from(el.children);
    el.textContent = `${label} `;
    for (const child of keep) el.appendChild(child);
  });
}

export function constellationName(index: number): string {
  return t(`constellation${Math.max(0, Math.min(7, index))}`);
}
